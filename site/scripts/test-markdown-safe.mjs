// Energy Research Warehouse (ERW) site, session 177: markdown is written into the page as HTML (lib/markdown.ts).
// A tag in a document must be shown as text, and a link must not carry a script.
//
//   node --import ./scripts/alias-register.mjs scripts/test-markdown-safe.mjs      (needs content/docs.json: npm run content)
//
// Also renders every document the site holds and fails if any result holds a tag that is not markdown's own.
import assert from "node:assert/strict";

const { render, safeHtml, safeHref, DOCS } = await import("../lib/markdown.ts");
let n = 0;
const test = (name, f) => { f(); n += 1; console.log(`ok   ${name}`); };
const at = "docs/digest/2026-10-10.md";

test("a script, an event handler and a frame in a document are text, not markup", () => {
  for (const bad of ['<script>alert(1)</script>', '<img src=x onerror="alert(1)">', '<iframe src="https://evil.example"></iframe>', '<svg onload=alert(1)>', '<a href="javascript:alert(1)">x</a>',
    '<style>body{display:none}</style>', '<form action="https://evil.example"><input name=q></form>', '<!-- a --><script>alert(1)</script><!-- b -->', '<a id="x" onclick="alert(1)">']) {
    const html = render(`A story about ${bad} prices.\n\n${bad}\n`, at);
    assert.ok(!/<(script|img|iframe|svg|style|form|input)\b/i.test(html), `${bad} -> ${html}`);
    assert.ok(!/<[^>]*\son[a-z]+\s*=/i.test(html), `${bad} -> ${html}`);
    assert.ok(!/href="javascript:/i.test(html), `${bad} -> ${html}`);
    assert.ok(html.includes("&lt;"), `${bad} is shown as text`);
  }
});

test("a link or an image with a script address goes nowhere; the usual ones are kept", () => {
  const html = render("[a](javascript:alert(1)) [b](data:text/html,x) [c](vbscript:x) ![d](javascript:alert(1)) [e](https://www.eia.gov/x) [f](mailto:a@example.com) [g](/storage) [h](#top) [i](../methods/storage.md)", at);
  assert.ok(!/javascript:|vbscript:|data:text/i.test(html), html);
  assert.equal((html.match(/href="#"/g) ?? []).length, 3);
  for (const kept of ['href="https://www.eia.gov/x"', 'href="mailto:a@example.com"', "/storage", 'href="#top"', "/data/methods/storage"]) assert.ok(html.includes(kept), `${kept} in ${html}`);
  assert.equal(safeHref("JaVaScRiPt:alert(1)"), false);
  assert.equal(safeHref(" javascript:alert(1)"), false);
  assert.equal(safeHref("https://example.com"), true);
  assert.equal(safeHref("docs/methods/storage.md"), true);
});

test("what the documents use is kept: a comment, an anchor, a line break, a subscript", () => {
  assert.equal(safeHtml("<!-- Generated by warehouse/news/brief.py -->\n"), "<!-- Generated by warehouse/news/brief.py -->\n");
  assert.equal(safeHtml('<a id="caiso"></a>\n'), '<a id="caiso"></a>\n');
  assert.equal(safeHtml("<br>"), "<br>");
  assert.equal(safeHtml("<sub>"), "<sub>");
  assert.equal(safeHtml("</sup>"), "</sup>");
  assert.ok(render('<a id="caiso"></a>\n\n## California\n', "docs/methods/storage.md").includes('<a id="caiso"></a>'));
  assert.ok(render("CO<sub>2</sub> per MWh", at).includes("CO<sub>2</sub>"));
});

test("a word in angle brackets is shown as the author wrote it", () => {
  const html = render('| a | b |\n|---|---|\n| cites each as "<title> [<id>], retrieved <date>" | consumption of N MW in <month> |\n', "docs/methods/thesis.md");
  for (const shown of ["&lt;title&gt;", "&lt;id&gt;", "&lt;date&gt;", "&lt;month&gt;"]) assert.ok(html.includes(shown), `${shown} in ${html}`);
  assert.ok(!/<title>|<month>/.test(html));
  assert.equal(safeHtml("AT&T &amp; <b>"), "AT&amp;T &amp; &lt;b&gt;");
});

test("markdown's own output is as it was", () => {
  const html = render("# Title\n\nSome **bold** and `code <b>` and a [link](https://example.com).\n\n| a | b |\n|---|---|\n| 1 | 2 |\n\n```\n<script>in a code block</script>\n```\n", at);
  for (const kept of ["<h1>Title</h1>", "<strong>bold</strong>", "<code>code &lt;b&gt;</code>", '<a href="https://example.com">link</a>', "<table>", "&lt;script&gt;in a code block&lt;/script&gt;"]) assert.ok(html.includes(kept), `${kept} in ${html}`);
});

test("every document the site holds renders with no tag that is not markdown's own", () => {
  const OWN = new Set(["p", "h1", "h2", "h3", "h4", "h5", "h6", "ul", "ol", "li", "a", "strong", "em", "code", "pre", "table", "thead", "tbody", "tr", "th", "td", "blockquote", "hr", "br", "img", "del", "span", "sub", "sup", "input"]);
  const sets = { digest: DOCS.digests, roundup: DOCS.weeklies, methods: DOCS.methods, grids: DOCS.grids, standard: { datastandard: DOCS.datastandard } };
  let files = 0;
  for (const [kind, set] of Object.entries(sets)) {
    for (const [name, md] of Object.entries(set ?? {})) {
      if (typeof md !== "string") continue;
      files += 1;
      const html = render(md, `docs/${kind}/${name}.md`).replace(/<!--(?:(?!-->)[\s\S])*-->/g, "");
      for (const m of html.matchAll(/<\/?([a-zA-Z][a-zA-Z0-9]*)\b([^>]*)>/g)) {
        assert.ok(OWN.has(m[1].toLowerCase()), `${kind}/${name}: <${m[1]}>`);
        assert.ok(!/\son[a-z]+\s*=/i.test(m[2]), `${kind}/${name}: an event handler in <${m[1]}${m[2]}>`);
      }
      assert.ok(!/(href|src)="(?!https?:|mailto:|\/|#)[a-z][a-z0-9+.-]*:/i.test(html), `${kind}/${name}: a link with another scheme`);
    }
  }
  assert.ok(files >= 50, `${files} documents`);
  console.log(`     ${files} documents rendered`);
});

console.log(`${n} tests passed`);
