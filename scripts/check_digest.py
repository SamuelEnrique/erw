#!/usr/bin/env python3
"""Every figure of every Energy Digest, traced to the warehouse table it names (session 402).

Energy Research Warehouse (ERW). The Digest (docs/digest/<date>.md, written by warehouse/news/brief.py) is markdown; the
site gives each figure of its numbers section and of its chart of the day a check key (site/lib/digest.ts). This
script reads those keys as the site makes them (site/scripts/digest-figures.mjs, run with node), and recomputes each
figure from the warehouse, by the Digest's own rule:

    digest_dam    the mean of the operating day's hourly day-ahead prices (the ISO's local day; every hour held),
                  exact and rounded half up to cents, as brief.mean2
    digest_rt     the real-time price at its interval, to two decimals
    digest_fuel   the EIA spot close on its trading day, to two decimals
    digest_demand the US48 demand at its hour, to the megawatt (session 804: the demand line)
    digest_chart  the chart's value and old record at their periods in the chart's table; its other figures are the
                  record's own statistics (the scan's), checked by scripts/check-values.mjs against the record

and the fun facts drawn from the warehouse (warehouse/news/facts/items/<date>.json, kind "warehouse"): a fuel's lowest
or highest close, and a state's share of a fuel in its net generation, recomputed; any other fun fact was checked word
for word against its stored source when it was written (warehouse/news/funfact.py) and is listed as such.

    python scripts/check_digest.py                       # the local CSVs (warehouse/output), read only
    python scripts/check_digest.py --in-dir DIR          # the CSVs of another copy
    python scripts/check_digest.py --supabase            # the live set, with the anon key (read only; ISO prices
                                                         # are held there for 35 days)
    python scripts/check_digest.py --figures FILE        # figures already written by digest-figures.mjs
    python scripts/check_digest.py --supabase --then-csv # the live set, then the CSVs for what it does not hold
                                                         # (session 498: one run traces every Digest)

Each figure is one line: ok, FAIL (the warehouse holds the period and gives another value), "revised" (session 2206:
the value differs, the row was retrieved after the issue was written, and both the issue and the retrieval fall within
the publisher's revision window of the figure's period, REVISION_DAYS: the publisher's revision, not a fault of the
issue; as scripts/check_roundup.py reads a Roundup's), or "not here" (the source read does not hold the period: an old
copy of the CSVs, or past the live set's window). Exit 1 when any figure fails, or when no figure could be checked; 0
otherwise. Writes nothing.
"""
import argparse
import json
import os
import re
import subprocess
import sys
import time
import urllib.parse
import urllib.error
import urllib.request
from datetime import datetime, timedelta, timezone
from decimal import ROUND_HALF_UP, Decimal
from zoneinfo import ZoneInfo

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SITE = os.path.join(ROOT, "site")
DIGEST = os.path.join(ROOT, "docs", "digest")
FACTS = os.path.join(ROOT, "warehouse", "news", "facts", "items")
TZ = {"ERCOT": "America/Chicago", "CAISO": "America/Los_Angeles", "NYISO": "America/New_York", "MISO": "Etc/GMT+5",
      "SPP": "America/Chicago", "ISO-NE": "America/New_York"}   # brief.py MAIN_HUBS: MISO's day is EST, all year
PREFIX = {"ERCOT": "ercot", "CAISO": "caiso", "NYISO": "nyiso", "MISO": "miso", "SPP": "spp", "ISO-NE": "isone"}


# Session 2206: how long after a period its publisher may still revise the value, in days, by table. An ISO resettles a
# real-time interval for about two months; a day-ahead price is settled within the week; EIA's weekly spot-price release
# restates recent days; a monthly EIA series (the chart's tables) is preliminary for about a year. A table not named has
# no window: a value that differs is a FAIL whenever it was retrieved. The days are this session's reading of the
# publishers' practice, not a figure of theirs (SESSION_2206_REPORT.md, "Decisions made without you").
REVISION_DAYS = {"iso_rtm_hub_prices": 60, "nyiso_rtm_zone_prices": 60, "isone_rtm_zone_prices": 60, "isone_rtm_zone_prices_hourly": 60,
                 "iso_dam_hub_prices": 7, "nyiso_dam_zone_prices": 7, "isone_dam_zone_prices": 7,
                 "eia_fuel_spot_prices": 14,
                 "eia_state_generation_monthly": 400, "eia_retail_electricity_prices": 400, "eia_retail_sales_monthly": 400}
GENERATED = re.compile(r"Generated by warehouse/news/brief\.py at (\d{4}-\d\d-\d\d \d\d:\d\d) UTC")


def written_at(date, digest_dir=None):
    """When the issue was written (UTC, "YYYY-MM-DDTHH:MM:00Z"), from its foot; None when the file or the line is not there."""
    p = os.path.join(digest_dir or DIGEST, f"{date}.md")
    if not os.path.exists(p):
        return None
    with open(p, encoding="utf-8") as f:
        m = GENERATED.search(f.read())
    return datetime.strptime(m.group(1), "%Y-%m-%d %H:%M").strftime("%Y-%m-%dT%H:%M:00Z") if m else None


def retrieved_at(src, table, entity, ts, variable=None):
    """When the row read was retrieved from its publisher (UTC, "YYYY-MM-DDTHH:MM:SSZ"), or None if not known."""
    if isinstance(src, Live):
        p = {"select": "retrieved_at", "table_name": f"eq.{table}", "entity": f"eq.{entity}", "ts_utc": f"eq.{ts}", "limit": "1"}
        if variable:
            p["variable"] = f"eq.{variable}"
        got = src._get(p)
        return iso_z(datetime.fromisoformat(got[0]["retrieved_at"].replace("Z", "+00:00"))) if got and got[0].get("retrieved_at") else None
    if isinstance(src, Csv):
        import pandas as pd
        path = os.path.join(src.dir, f"{table}.csv")
        if not os.path.exists(path):
            return None
        df = pd.read_csv(path, skiprows=header_rows(path), usecols=["entity", "variable", "ts_utc", "retrieved_at"], dtype=str)
        df = df[(df["entity"] == entity) & (df["ts_utc"] == ts)]
        if variable:
            df = df[df["variable"] == variable]
        return str(df["retrieved_at"].iloc[0]) if len(df) and str(df["retrieved_at"].iloc[0]) != "nan" else None
    return None


def compare(src, shown, got, written, table, entity, ts, variable=None, period=None):
    """(status, why) of a printed value against the row read now: ok when equal; "revised" when the row was retrieved
    after the issue was written and both the issue and the retrieval fall within the table's revision window counted
    from the figure's period (REVISION_DAYS); else FAIL. `period` is the figure's own day ("YYYY-MM-DD"; the row's
    timestamp when not given)."""
    if got == shown:
        return "ok", got
    when = retrieved_at(src, current(table), entity, ts, variable)
    days = REVISION_DAYS.get(current(table), REVISION_DAYS.get(table))
    if when and written and days is not None:
        p0 = datetime.strptime((period or ts)[:10], "%Y-%m-%d")
        edge = (p0 + timedelta(days=days)).strftime("%Y-%m-%dT%H:%M:%SZ")
        if when > written and written <= edge and when <= edge:
            return "revised", f"{got} (row retrieved {when}, after the issue was written {written}, both within {days} days of {p0:%Y-%m-%d}: the publisher's revision)"
    return "FAIL", f"{got}" + (f" (row retrieved {when})" if when else "")


def current(table):
    """A table consolidated in session 29 (warehouse/metadata/table_migrations.csv) is read from its new table."""
    m = re.fullmatch(r"(caiso|ercot|miso|spp)_(dam|rtm)_hub_prices", table)
    return f"iso_{m.group(2)}_hub_prices" if m else table


def mean2(values):
    """brief.mean2: exact on the values as written, rounded half up to cents."""
    vals = [Decimal(repr(float(v))) for v in values]
    return str((sum(vals) / len(vals)).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def chart_text(v):
    """daily_chart.num without its unit: 0 decimals from 10,000, 1 from 100, 2 from 1, else 4."""
    a = abs(float(v))
    nd = 0 if a >= 10000 else (1 if a >= 100 else (2 if a >= 1 else 4))
    return f"{float(v):,.{nd}f}"


def iso_z(t):
    return t.astimezone(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def day_bounds(day, tz):
    z = ZoneInfo(tz)
    d = datetime.strptime(day, "%Y-%m-%d")
    start = d.replace(tzinfo=z)
    end = (d + timedelta(days=1)).replace(tzinfo=z)
    # aware datetimes of one zone subtract as wall clocks: the hours are counted in UTC (25 on the day the clocks go back)
    return start, end, int(round((end.astimezone(timezone.utc) - start.astimezone(timezone.utc)).total_seconds() / 3600))


def header_rows(path):
    """The "#" lines before the column row (warehouse/connectors/iso_prices.py header_rows; connectors share no code)."""
    n = 0
    with open(path, encoding="utf-8") as f:
        for line in f:
            if not line.startswith("#"):
                break
            n += 1
    return n


