NAT = ["UK Total", "Scotland", "Wales", "Northern Ireland", "England"]


def head(years=(2004, 2005), digit=False, nations=NAT):
    return [f"{y} {n}" + ("6" if digit and y == 2005 and n == "England" else "") for y in years for n in nations]


def fuel_sheet(coal=10.0, extra=None, nations=NAT):
    cells = lambda v: [v] * (2 * len(nations))
    rows = [("Table 2: Generation of electricity by fuel",), ("This worksheet",),
            ("Table 2a: Electricity generated by fuel for Scotland, Wales, Northern Ireland and England",),
            ("Generator type", "Fuel", *head(nations=nations)),
            ("Major power producers", "Coal", *cells(coal)), ("Major power producers", "Wind [Note 1]", *cells("[x]")),
            ("Major power producers", "Gas", *cells(20.0)), ("Major power producers", "Total major power producers", *cells(30.0)),
            ("Other generators", "Solar", *cells(1.0)), ("Other generators", "Total other generators", *cells(1.0)),
            ("All generating companies", "Coal", *cells(999.0)), ("All generating companies", "Total all generating companies", *cells(1.0))]
    if extra:
        rows.insert(9, extra)
    return rows


def supply_sheet(drop=None, digit=False):
    rows = [("Table 1: Generation and supply",), ("This worksheet contains one table.",), ("Table 1",),
            ("Components of electricity generation and supply", *head(digit=digit))]
    for i, lab in enumerate(A.SUPPLY):
        if lab != drop:
            rows.append((lab + (" [note 10]" if "storage" in lab else ""), *([float(i)] * 10)))
    return rows


class Parse(unittest.TestCase):
    def test_fuel(self):
        v = A.parse_fuel(fuel_sheet())
        self.assertEqual(v[("scotland", "mpp_coal", 2005)][0], 10.0)
        self.assertEqual(v[("england", "other_total", 2004)][0], 1.0)
        self.assertNotIn(("uk", "mpp_wind", 2004), v)
        self.assertFalse([k for k in v if "all" in k[1]])
        self.assertEqual(len(v), 5 * 5 * 2)

    def test_supply(self):
        v = A.parse_supply(supply_sheet(digit=True))
        self.assertIn(("england", "sales", 2005), v)
        self.assertEqual(v[("wales", "own_use_mpp", 2004)][0], 5.0)
        self.assertEqual(len(v), len(A.SUPPLY) * 10)

    def test_stops(self):
        for fn, arg in ((A.parse_fuel, fuel_sheet(coal=25.0)), (A.parse_fuel, fuel_sheet(extra=("Other generators", "Peat", *([1.0] * 10))))
                        , (A.parse_fuel, fuel_sheet(nations=NAT[:4] + ["Isle of Man"])), (A.parse_supply, supply_sheet(drop="Transmission losses"))):
            with self.assertRaises(RuntimeError):
                fn(arg)

    def test_frame_units(self):
        import io
        import openpyxl
        wb = openpyxl.Workbook()
        wb.active.title = "Generation and supply"
        for r in supply_sheet():
            wb.active.append(list(r))
        ws = wb.create_sheet("Electricity generation by fuel")
        for r in fuel_sheet():
            ws.append(list(r))
        f = io.BytesIO()
        wb.save(f)
        t = A.parse(f.getvalue(), {"source": "s", "source_url": "u", "retrieved_at": "r", "vintage": ""})
        r = dict(zip(t.entity + "|" + t.ts_utc.str[:4], zip(t.variable, t.value, t.geo)))
        self.assertEqual(r["desnz:scotland:mpp_coal|2004"], ("generation", 10000.0, "GB-SCT"))
        self.assertEqual(r["desnz:uk:transfer_to_europe|2005"][0], "net_transfers")
        self.assertEqual(r["desnz:northern_ireland:sales|2004"][2], "GB-NIR")


