"""Session 498: every number of the periodicals traced (roadmap v4 draft item 1).

What is held here, without a network and without a database: scripts/check_roundup.py (new) reads each Roundup's
numbers section and recomputes it by roundup.py's rules from a source (the CSVs or the live set); a single row that
differs and was retrieved after the issue was written is "revised" (the publisher's revision), one retrieved before
it a FAIL; a stated gap is listed, not checked. scripts/check_digest.py --supabase --then-csv reads from the CSVs what
the live set does not hold, and says so on the line. Neither script nor the report holds an em or en dash.
"""
import contextlib
import csv
import importlib.util
import io
import json
import os
import sys
import tempfile
import unittest

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCRIPTS = os.path.join(ROOT, "scripts")
REPORT = os.path.join(ROOT, "archive", "sessions", "SESSION_498_REPORT.md")
COLS = ["entity", "variable", "ts_utc", "value", "unit", "freq", "geo", "market", "node", "source", "source_url", "retrieved_at", "vintage"]


def load(name, file):
    if SCRIPTS not in sys.path:
        sys.path.insert(0, SCRIPTS)
    spec = importlib.util.spec_from_file_location(name, os.path.join(SCRIPTS, file))
    m = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(m)
    return m


def write_csvs(d, rows):
    for table, rs in rows.items():
        with open(os.path.join(d, f"{table}.csv"), "w", encoding="utf-8", newline="") as f:
            f.write("# a test table\n")
            w = csv.DictWriter(f, COLS)
            w.writeheader()
            for e, v, ts, val, got in rs:
                w.writerow({"entity": e, "variable": v, "ts_utc": ts, "value": val, "retrieved_at": got})


# a Roundup of the form roundup.py writes since session 21 (numbers section, footnotes, the foot's comment)
ROUNDUP = """# ERW's Roundup, 2026-W41

## ERW's Numbers This Week

**Day-ahead average, main hub, over the ISO's local week, and the change from the week before**

| ISO | Hub or zone | This week USD/MWh | Week before USD/MWh | Change | Table |
|---|---|---|---|---|---|
| ERCOT | HB_NORTH | 15.00 | 10.00 | +5.00 | [1] |
| MISO | INDIANA.HUB | not in the warehouse (0 of 168 hours) | 12.00 | not computed | [1] |

**Highest real-time price of the week:** 900.50 USD/MWh at SPPNORTH_HUB (SPP), interval starting 2026-10-08 17:45 local (2026-10-08 22:45 UTC), lmp_rtm_15m_mean [4].

| Price | Last close this week | Last close before | Change | Table |
|---|---|---|---|---|
| Henry Hub natural gas | 3.03 USD/MMBtu on 2026-10-06 | 2.90 on 2026-10-02 | +0.13 (+4.5%) | [5] |

**US48 peak demand of the week:** 575,114 MW in the hour starting 2026-10-08 22:00 UTC (Thursday 2026-10-08, 18:00 Eastern), from 144 hours [6].

Tables: [1] `iso_dam_hub_prices` (ercot:NP4-190-CD); [4] `iso_rtm_hub_prices` (spp:RTBM); [5] `eia_fuel_spot_prices` (eia); [6] `eia930_all_demand` (us48)

## ERW's Chart of the Week

<!-- Generated by warehouse/news/roundup.py at 2026-10-11 23:22 UTC; run log x; model none. -->
"""


class TheRoundupChecker(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.r = load("s498_check_roundup", "check_roundup.py")
        cls.cd = cls.r.cd

    def _rows(self):
        # ERCOT's local week of 2026-W41 (Chicago, CDT): 2026-10-05 05:00 UTC to 2026-10-12 05:00 UTC, 168 hours
        def week(mon_day, value):
            out = []
            for h in range(168):
                day, hour = divmod(h + 5, 24)
                out.append(("ercot:HB_NORTH", "lmp_dam", f"2026-10-{mon_day + day:02d}T{hour:02d}:00:00Z", value, "2026-10-12T00:00:00Z"))
            return out
        return {
            "iso_dam_hub_prices": week(5, 15),   # the week before is not held: "not here"
            "iso_rtm_hub_prices": [("spp:SPPNORTH_HUB", "lmp_rtm_15m_mean", "2026-10-08T22:45:00Z", 42.0, "2026-10-14T00:00:00Z")],
            "eia_fuel_spot_prices": [("eia:henry_hub", "spot_price", "2026-10-06T00:00:00Z", 3.03, "2026-10-09T00:00:00Z"),
                                     ("eia:henry_hub", "spot_price", "2026-10-02T00:00:00Z", 2.95, "2026-10-09T00:00:00Z")],
            "eia930_all_demand": [("eia930:US48", "demand_mw", "2026-10-08T22:00:00Z", 575114, "2026-10-10T00:00:00Z")],
        }

    def test_each_kind_of_figure_is_ok_failed_revised_gap_or_not_held(self):
        r = self.r
        with tempfile.TemporaryDirectory() as d:
            write_csvs(d, self._rows())
            src = self.cd.Csv(d)
            got = {key: f(src) for key, _, f in r.checks("2026-W41", ROUNDUP)}
        st = {k: v[0] for k, v in got.items()}
        self.assertEqual(st["rdp_dam|ERCOT|iso_dam_hub_prices|HB_NORTH|week"], "ok")
        self.assertEqual(st["rdp_dam|ERCOT|iso_dam_hub_prices|HB_NORTH|week before"], "not here")   # no rows that week
        self.assertEqual(st["rdp_change|ERCOT|HB_NORTH"], "ok")                                     # 15.00 - 10.00
        self.assertEqual(st["rdp_dam|MISO|iso_dam_hub_prices|INDIANA.HUB|week"], "gap")
        # 900.50 printed, 42.00 held, the row retrieved after the issue's foot (2026-10-11 23:22 UTC): the publisher's
        self.assertEqual(st["rdp_rt|iso_rtm_hub_prices|spp:SPPNORTH_HUB|lmp_rtm_15m_mean|2026-10-08T22:45:00Z"], "revised")
        self.assertEqual(st["rdp_fuel|eia_fuel_spot_prices|eia:henry_hub|2026-10-06"], "ok")
        # 2.90 printed, 2.95 held, the row retrieved before the issue was written: a fault
        self.assertEqual(st["rdp_fuel|eia_fuel_spot_prices|eia:henry_hub|2026-10-02"], "FAIL")
        self.assertEqual(st["rdp_fuel_change|eia:henry_hub|2026-10-06|2026-10-02"], "ok")
        self.assertEqual(st["rdp_us48|eia930_all_demand|eia930:US48|demand_mw|2026-10-08T22:00:00Z"], "ok")

    def test_the_rules_are_roundups(self):
        r = self.r
        self.assertEqual(str(r.week_start("2026-W41")), "2026-10-05")
        s, e, hours = r.local_week(r.week_start("2026-W44"), "America/Chicago")   # the week the clocks go back (1 November)
        self.assertEqual(hours, 169)
        self.assertEqual(r.local_week(r.week_start("2026-W44"), "Etc/GMT+5")[2], 168)   # MISO's week is EST
        self.assertEqual(r.written_at(ROUNDUP), "2026-10-11T23:22:00Z")
        self.assertIsNone(r.section("# a Roundup with no numbers"))

    def test_every_roundup_on_file_has_its_numbers_parsed(self):
        r = self.r
        rs = r.roundups()
        if not rs:
            self.skipTest("no Roundup in this checkout")
        for label, md in rs:
            cs = r.checks(label, md)
            self.assertGreaterEqual(len(cs), 20, label)                       # six hubs, the change, rt, fuels, US48
            kinds = {k.split("|")[0] for k, _, _ in cs}
            self.assertTrue({"rdp_dam", "rdp_rt", "rdp_fuel", "rdp_us48"} <= kinds, label)
            self.assertIsNotNone(r.written_at(md), label)


class TheDigestCheckerThenCsv(unittest.TestCase):
    def test_a_figure_the_live_set_does_not_hold_is_read_from_the_csvs(self):
        cd = load("s498_check_digest", "check_digest.py")

        class NoLive(cd.Csv):   # a live set that holds nothing (no network in a test)
            name = "supabase"

            def __init__(self):
                super().__init__(os.devnull)

            def describe(self):
                return "a live set that holds nothing"

            def rows(self, *a, **k):
                return []
        cd.Live = NoLive
        fig = {"key": "digest_fuel|eia_fuel_spot_prices|eia:henry_hub|2026-09-24", "raw": "3.10", "text": "3.10", "held": False}
        data = {"holds_on": "2026-10-21", "digests": {"2026-09-25": {"figures": [fig], "chart": {}}}}
        with tempfile.TemporaryDirectory() as d:
            write_csvs(d, {"eia_fuel_spot_prices": [("eia:henry_hub", "spot_price", "2026-09-24T00:00:00Z", 3.1, "2026-09-26T00:00:00Z")]})
            fp = os.path.join(d, "figures.json")
            json.dump(data, open(fp, "w", encoding="utf-8"))
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                code = cd.main(["--supabase", "--then-csv", "--in-dir", d, "--figures", fp, "--date", "2026-09-25"])
            line = [l for l in out.getvalue().splitlines() if "digest_fuel" in l][0]
            self.assertTrue(line.startswith("ok"), line)
            self.assertIn("(the CSVs; the live set: no close on 2026-09-24)", line)
            self.assertEqual(code, 0)
            out = io.StringIO()
            with contextlib.redirect_stdout(out):
                code = cd.main(["--supabase", "--in-dir", d, "--figures", fp, "--date", "2026-09-25"])   # without the flag
            self.assertTrue([l for l in out.getvalue().splitlines() if "digest_fuel" in l][0].startswith("not here"))


class NoDash(unittest.TestCase):
    def test_no_em_or_en_dash(self):
        for p in (os.path.join(SCRIPTS, "check_roundup.py"), os.path.join(SCRIPTS, "check_digest.py"), REPORT):
            if os.path.exists(p):
                text = open(p, encoding="utf-8").read()
                self.assertNotIn("—", text, p)
                self.assertNotIn("–", text, p)


