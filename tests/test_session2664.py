def sheet(names=NEW, year=2025, tpp=60.0, losses=10.0, drop_col=False):
    def row(label, e=None, ren=(None, None, None, None)):
        return (label, *ren, e)
    heads = names["heads"][:3] + (("Other, million kWh",) if drop_col else names["heads"][3:])
    final = names["final"] if names is NEW else "3. Final consumption"
    rows = [(f"Fuel and energy balance of the Republic of Kazakhstan for {year} in physical terms", None, None, None, None, None),
            (None,) * 6, (None,) * 6, (None, "Renewable energy sources", None, None, None, "Electricity, million kWh "),
            (None, *heads, None), ("Calorific value", 3.6, 3.6, 3.6, 3.6, 3.6),
            row("1. Total energy OTAL ENERGY SUPPLY"),
            row("Production (extraction) of primary energy (+)", None, (9.0, 2.0, 5.0, 0.5)),
            row(names["imports"], 5.0), row(names["exports"], -3.0), row(names["stat"], -1.0),
            row("2. Transformation, energy consumption sector, losses"),
            row("Transformation Sector - Login", 0),
            row(names["tpp"], None),
            row(names["exit"], 100.0), row(names["tpp"], tpp), row(names["tpp2"], 10.0), row(names["chpp"], 25.0), row(names["chpp2"], 5.0),
            row("Consumption in the energy sector (own needs)", 20.0), row(names["tpp"], 6.0),
            row(names["losses"], losses), row("Available for final consumption", 72.0),
            row(final, 73.0 if names is NEW else 73.0)]
    if names is not NEW:
        rows.append(row("Final energy consumption", 73.0))
    rows += [row("Industry sector", 40.0), row("Transport sector", 3.0), row("Other", 30.0), row("Commercial and government services", 12.0),
             row("Housing sector", 15.0), row("Agriculture/forestry", 3.0)]
    return rows


class Parse(unittest.TestCase):
    def test_both_editions(self):
        for names, year in ((NEW, 2025), (OLD, 2023)):
            v = A.parse_sheet(sheet(names, year), year)
            self.assertEqual(v["output"][0], 100.0)
            self.assertEqual(v["tpp_main"][0], 60.0)
            self.assertEqual(v["exports"][0], 3.0)
            self.assertEqual(v["statistical_difference"][0], -1.0)
            self.assertEqual(v["consumption"][0], 73.0)
            self.assertEqual(v["wind"][0], 5.0)
            self.assertNotIn("available", v)
        t = A.frame({2025: A.parse_sheet(sheet(), 2025)}, {2025: BASE})
        r = {(e, x) for e, x in zip(t.entity, t.variable)}
        self.assertIn(("statkz:kz:hydro", "generation"), r)
        self.assertIn(("statkz:kz:own_use", "own_use"), r)
        self.assertEqual(t.value[t.entity == "statkz:kz:output"].iloc[0], 100000.0)
        self.assertEqual(len(t), 21)

    def test_stops(self):
        for rows, year in ((sheet(year=2024), 2025), (sheet(drop_col=True), 2025), (sheet(tpp=65.0), 2025), (sheet(losses=15.0), 2025),
                           ([r for r in sheet() if r[0] != "Housing sector"], 2025)):
            with self.assertRaises(RuntimeError):
                A.parse_sheet(rows, year)


