BASE = {"source": "s", "source_url": "u", "retrieved_at": "r", "vintage": ""}
Y = [2021, 2022, 2023, 2024]


def book(t1_produced=100, steam=40, extra=None):
    wb = openpyxl.Workbook()
    s1 = wb.active
    s1.title = "1"
    s1.append(["x", None, None, None, "Main indicators in the electric energy sector for the years (2021-2024)"])
    s1.append(["x", *Y, "Rate of change", "Indicators"])
    s1.append(["x", 70, 70, 70, 70, 1.4, "Number of stations (generation or production)"])
    s1.append(["x", 160, 160, 160, 160, 1.0, "Total production of the electricity energy system (MWh) …… (1)".replace("…", ".")])
    s1.append(["x", t1_produced, 100, 100, 100, 1.0, "Quantity of electricity produced (MWh) ........(2)"])
    s1.append(["x", 50, 50, 50, 50, 1.0, "Quantity of electricity sold to consumers (MWh)"])
    s1.append(["x", 55, 55, 55, 55, 1.0, "Quantity of imported electricity (MWh) .........(3)"])
    s1.append(["x", 5, 5, 5, 5, 1.0, "The amount of electricity imported from the Kurdistan Region (MWh)...(4)"])
    s1.append(["x", 9, 9, 9, 9, 1.0, "Revenues generated by the electrical system (billion dinars)"])
    s2 = wb.create_sheet("2")
    s2.append(["x", None, None, "Quantity of electrical energy produced by means ofgenerating electricit for the years (2021-2024)"])
    s2.append(["x", *Y, "Power stations"])
    rows = [(steam, "Steam plants"), (50, "Gas stations"), (5, "Diesel stations + Hyundai diesels + STX diesels"),
            (5, "Hydroelectric stations"), (100, "Total Energy Generated"), (55, "Imported energy + investment"),
            (5, "Imported from the Kurdistan region"), (60, "Grand total"), (160, "Total Electrical Energy")]
    if extra:
        rows.append(extra)
    for v, lab in rows:
        s2.append(["x", v, v, v, v, lab])
    s2.append(["x", None, None, "The amount of internal consumption and losses in transmission and electrical energy distribution"])
    s2.append(["x", *Y, "The details"])
    for v, lab in ((1, "Internal consumption and losses in production plants"), (2, "Internal consumption and losses in transportation networks"),
                   (7, "Internal consumption and losses in distribution networks"), (10, "Total")):
        s2.append(["x", v, v, v, v, lab])
    f = io.BytesIO()
    wb.save(f)
    return f.getvalue()


class Parse(unittest.TestCase):
    def test_rows(self):
        t = A.parse(book(), BASE)
        r = {(e, s[:4]): (v, x) for e, s, v, x in zip(t.entity, t.ts_utc, t.variable, t.value)}
        self.assertEqual(r[("cosit:iq:steam", "2024")], ("generation", 40.0))
        self.assertEqual(r[("cosit:iq:kurdistan", "2021")], ("purchases", 5.0))
        self.assertEqual(r[("cosit:iq:total", "2022")], ("supply", 160.0))
        self.assertEqual(r[("cosit:iq:sold", "2023")], ("sales", 50.0))
        self.assertEqual(r[("cosit:iq:losses_total", "2024")], ("losses", 10.0))
        self.assertEqual(len(t), 14 * 4)
        self.assertFalse(t.node.str.contains("Revenues|stations \\(generation", regex=True).any())

    def test_stops(self):
        for content in (book(steam=45), book(t1_produced=110), book(extra=(1, "Nuclear plants"))):
            with self.assertRaises(RuntimeError):
                A.parse(content, BASE)


