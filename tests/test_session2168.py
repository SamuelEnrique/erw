HEAD = ["Generator type", "Fuel", "Quarter 1 2025", "Quarter 2 2026 [provisional]"]


def workbook(rows, sheet="Quarter"):
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = sheet
    for r in rows:
        ws.append(r)
    b = io.BytesIO()
    wb.save(b)
    return b.getvalue()


ROWS = [["Table 5.1a: fuel used in electricity generation (Mtoe)"], HEAD, ["Major power producers", "Gas (TWh)", 57.9, 31.5],
        ["Table 5.1b: electricity generated by fuel (TWh)"], HEAD, ["All generating companies", "Total wind", 25.1, 19.2],
        ["All generating companies", "Solar", "[x]", 8.4], ["All generating companies", "Total all generating companies", 80.0, 68.6],
        ["Table 5.1c: electricity supplied by fuel (TWh)"], HEAD, ["Major power producers", "Pumped storage (net supply)", -0.3, -0.2],
        ["Table 5.1d: Shares of electricity generated by fuel (%)"], HEAD, ["All generating companies", "Renewable generation share", 50, 55.8]]


class Build(unittest.TestCase):
    def test_rows(self):
        t = D.build(workbook(ROWS), "u", "r", "")
        self.assertEqual(set(t.variable), {"generated", "supplied"})
        w = t[(t.entity == "desnz_et51:all_generating_companies:total_wind") & (t.ts_utc == "2026-04-01T00:00:00Z")].iloc[0]
        self.assertEqual((w.value, w.unit, w.freq, w.geo, w.x_provisional), (19200000.0, "MWh", "P3M", "GB", "yes"))
        self.assertEqual(t[(t.entity == "desnz_et51:all_generating_companies:total_wind") & (t.ts_utc == "2025-01-01T00:00:00Z")].iloc[0].x_provisional, "no")
        self.assertEqual(len(t[t.entity == "desnz_et51:all_generating_companies:solar"]), 1)
        p = t[t.entity == "desnz_et51:major_power_producers:pumped_storage"]
        self.assertEqual((sorted(p.value), set(p.variable)), ([-300000.0, -200000.0], {"supplied"}))
        self.assertEqual(len(t), 2 + 1 + 2 + 2)

    def test_stops(self):
        for bad in (workbook(ROWS, sheet="Annual"), workbook(ROWS[3:5] + [["All generating companies", "Coal", 1, 2]]),
                    workbook([ROWS[3], ["Generator type", "Fuel", "2025 Q1"], ROWS[8], HEAD]),
                    workbook([ROWS[3], HEAD, ["All generating companies", "Coal", "n/a", 1], ROWS[8], HEAD])):
            with self.assertRaises(RuntimeError):
                D.build(bad, "u", "r", "")


