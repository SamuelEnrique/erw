"""Session 2168: the UK's electricity generated and supplied by fuel (DESNZ, Energy Trends table 5.1).

Energy Research Warehouse (ERW). Tests warehouse/connectors/desnz_energy_trends.py on a workbook built here in table
ET 5.1's "Quarter" form (made up for the test, not DESNZ's): tables 5.1b and 5.1c taken, 5.1a left, TWh written as MWh,
a quarter as its first day, "[x]" left out, a provisional quarter kept and marked, a negative net supply kept; a sheet
without the tables, a header not a quarter and a value that is neither a number nor "[x]" stopping the run; the verdict,
the sector rule and the holds. No network.

    python -m unittest tests.test_session2168 -v
"""

