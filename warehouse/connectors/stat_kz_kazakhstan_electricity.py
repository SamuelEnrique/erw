#!/usr/bin/env python3
"""Kazakhstan's electricity a year, 2022 to 2025: output by plant class, hydro, solar, wind and biogas production, imports,
exports, the energy sector's own use, losses and final consumption by sector, from the electricity column of the fuel and
energy balance in physical terms that the Bureau of National Statistics (Agency for Strategic Planning and Reforms) publishes
each year (session 2664, chain 133, the session's own choice; the ERW held Kazakhstan only in EIA's world tables, and session
2360 found KEGOC's figures only in prose).

Energy Research Warehouse (ERW) connector. One series table, warehouse/output/stat_kz_kazakhstan_electricity_annual.csv, from
four workbooks (no key), one a year, each the balance's English edition, sheet "1" (in physical terms):

    https://stat.gov.kz/api/iblock/element/<id>/file/en/     (2022 75937, 2023 205511, 2024 411633, 2025 411634)

    entity      statkz:kz:<item>: output (the transformation sector's electricity), tpp_main, tpp_secondary, chpp_main,
                chpp_secondary (variable generation, by plant class and activity); hydro, solar, wind, biogas (generation,
                primary production); imports; exports (as a positive quantity); own_use; losses; consumption (final energy
                consumption), industry, transport, other, households, services, agriculture (consumption); statistical_difference
    unit        MWh (the balance's million kWh times 1,000); ts_utc the year's first day; freq P1Y; geo KZ
    node        the row's label as the edition gives it (and, for the renewables, their column)

Each sheet is checked for its title ("Fuel and energy balance of the Republic of Kazakhstan for <year> in physical terms", the
year the workbook was asked for) and its column headers (electricity and the four renewables, in million kWh). Each row is found
by its label within its section (total supply, the transformation sector's exit, final consumption); the editions name the same
rows differently (2025: "Imports (+)", "Statistical differences", "Electricity plants (TPP)"; 2022 to 2024: "import",
"Statistical discrepancies", "Power plants (TPP) ... - electricity generation"), and a row found under none of its names stops the
run. A blank cell has no row; nothing is filled. Checks, each within 1 million kWh: the four plant classes add to the output; the
output, imports, exports, own use and losses make the energy available for final consumption; that, less the statistical
difference, is the final consumption; industry, transport and the other sectors add to it. The plant classes are not comparable
across 2024 and 2025: the 2025 edition puts most output under electricity plants (main activity), the earlier ones under CHP
plants. The 2021 edition (37685), in GWh and with the IEA's row names, is not read.

    python warehouse/connectors/stat_kz_kazakhstan_electricity.py [--offline] [--fresh] [--out-dir DIR]

Ceiling: four requests a run (one a workbook; each answer is the file under /upload/iblock/ on the same host), saved in
warehouse/raw/stat_kz/ and reused unless --fresh; --offline asks nothing. stat.gov.kz's robots file closes Bitrix's system
paths and some query parameters, not /api/iblock/ or /upload/ (session 2664). License: the Bureau's conditions for the use of
official statistical information (stat.gov.kz/en/description/): use for any purposes, freely, free of charge, with a reference
to the source: public.
"""

import argparse
import datetime as dt
import io
import os
import sys
import traceback

import openpyxl
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import iso_prices as ip  # noqa: E402

NAME = "stat_kz_kazakhstan_electricity_annual"
CONNECTOR = "stat_kz"
SOURCE = "stat_kz:fuel_energy_balance_physical"
HOST = "stat.gov.kz"
FILES = {2022: 75937, 2023: 205511, 2024: 411633, 2025: 411634}
URL = "https://stat.gov.kz/api/iblock/element/{}/file/en/"
PAGE = "https://stat.gov.kz/en/industries/business-statistics/stat-energy/"
TERMS = "https://stat.gov.kz/en/description/"
UA = {"User-Agent": "Mozilla/5.0 (compatible; ERW-connector/0.1; +https://github.com/SamuelEnrique/erw)"}
CITATION = ("Bureau of National Statistics of the Agency for Strategic Planning and Reforms of the Republic of Kazakhstan, Fuel and "
            "energy balance of the Republic of Kazakhstan, in physical terms")
SHEET = "1"
# a renewable column's header begins with one of these (the 2025 edition's, then the 2022 to 2024 editions')
RENEW = {"hydro": ("Hydropower, million kWh", "Electricity generated by hydroelectric power plants, million kWh"),
         "solar": ("Solar energy, million kWh", "Electricity produced by solar power plants, million kWh"),
         "wind": ("Wind energy, million kWh", "Electricity generated by wind farms, million kWh"),
         "biogas": ("Biogas plants, million kWh", "Electricity from biogas produced by biogas plants, million kWh")}
# (section start, row labels, ERW item, variable): a label ending in * matches as a prefix; exports are stored as a positive quantity
TOP = ("1. Total energy*", "1. TOTAL ENERGY*")
EXIT = ("Transformation Sector - Exit*", "Conversion Sector - Exit*")
FINAL = ("3. Final*",)
ROWS = [
    (TOP, ("Imports (+)", "import"), "imports", "imports"),
    (TOP, ("Exports (-)", "export"), "exports", "exports"),
    (TOP, ("Statistical differences", "Statistical discrepancies"), "statistical_difference", "statistical_difference"),
    (EXIT, EXIT, "output", "generation"),
    (EXIT, ("Electricity plants (TPP) (main activity)", "Power plants (TPP) (main activity) - electricity generation"), "tpp_main", "generation"),
    (EXIT, ("Electricity plants (TPP) (secondary activity)", "Power plants (TPP) (secondary activity) - electricity generation"),
     "tpp_secondary", "generation"),
    (EXIT, ("Combined Heat and Power Plants (CHPP) (main activity)*",), "chpp_main", "generation"),
    (EXIT, ("Combined Heat and Power Plants (CHPP) (secondary activity)*",), "chpp_secondary", "generation"),
    (TOP, ("Consumption in the energy sector (own needs)",), "own_use", "own_use"),
    (TOP, ("Losses during the technological process, transportation and distribution*",), "losses", "losses"),
    (TOP, ("Available for final consumption",), "available", None),
    (FINAL, ("3. Final energy consumption", "Final energy consumption"), "consumption", "consumption"),
    (FINAL, ("Industry sector",), "industry", "consumption"),
    (FINAL, ("Transport sector",), "transport", "consumption"),
    (FINAL, ("Other",), "other", "consumption"),
    (FINAL, ("Housing sector",), "households", "consumption"),
    (FINAL, ("Commercial and government services",), "services", "consumption"),
    (FINAL, ("Agriculture/forestry",), "agriculture", "consumption"),
]
PRIMARY = ("Production (extraction) of primary energy*",)
X_COLS = []


def is_num(v):
    return isinstance(v, (int, float)) and not isinstance(v, bool)


def lab(v):
    return " ".join(str(v).split()) if v is not None else ""


def match(label, aliases):
    return any(label == x or (x.endswith("*") and label.startswith(x[:-1])) for x in aliases)


def parse_sheet(rows, year):
    title = lab(rows[0][0]) if rows and rows[0] else ""
    if title != f"Fuel and energy balance of the Republic of Kazakhstan for {year} in physical terms":
        raise RuntimeError(f"{year}: the title is {title!r}")
    cols, heads_seen = {}, {}
    for r in rows[:6]:
        for j, x in enumerate(r):
            s = lab(x)
            if s.startswith("Electricity, million kWh"):
                cols["electricity"] = j
            for item, heads in RENEW.items():
                if any(s.startswith(h) for h in heads):
                    cols[item] = j
                    heads_seen[item] = s
    if set(cols) != {"electricity", *RENEW}:
        raise RuntimeError(f"{year}: the columns found are {sorted(cols)}")
    labels = [lab(r[0]) if r else "" for r in rows]
    out = {}
    for section, aliases, item, _ in ROWS:
        start = next((i for i, s in enumerate(labels) if match(s, section)), None)
        if start is None:
            raise RuntimeError(f"{year}: the section {section[0]!r} not found")
        i = next((k for k in range(start, len(labels)) if match(labels[k], aliases)), None)
        if i is None:
            raise RuntimeError(f"{year}: the row {aliases[0]!r} not found")
        v = rows[i][cols["electricity"]] if cols["electricity"] < len(rows[i]) else None
        if is_num(v):
            out[item] = (abs(float(v)) if item == "exports" else float(v), labels[i])
    prim = next((k for k, s in enumerate(labels) if match(s, PRIMARY)), None)
    if prim is None:
        raise RuntimeError(f"{year}: the primary production row not found")
    for item in RENEW:
        v = rows[prim][cols[item]] if cols[item] < len(rows[prim]) else None
        if is_num(v):
            out[item] = (float(v), f"{labels[prim]}: {heads_seen[item]}")
    g = lambda k: out.get(k, (0.0, ""))[0]
    for parts, whole in ((("tpp_main", "tpp_secondary", "chpp_main", "chpp_secondary"), "output"), (("industry", "transport", "other"), "consumption")):
        s = sum(g(k) for k in parts)
        if abs(s - g(whole)) > 1:
            raise RuntimeError(f"{year}: {'+'.join(parts)} make {s:,.2f} million kWh, {whole} {g(whole):,.2f}")
    avail = g("output") + g("imports") - g("exports") - g("own_use") - g("losses")
    if abs(avail - g("available")) > 1:
        raise RuntimeError(f"{year}: the balance makes {avail:,.2f} million kWh available, the sheet {g('available'):,.2f}")
    if abs(g("available") - g("statistical_difference") - g("consumption")) > 1:
        raise RuntimeError(f"{year}: available less the statistical difference is not the final consumption")
    out.pop("available", None)
    return out


def frame(by_year, bases):
    var = {item: v for _, _, item, v in ROWS if v}
    var.update({item: "generation" for item in RENEW})
    out = [dict(entity=f"statkz:kz:{item}", variable=var[item], ts_utc=f"{y}-01-01T00:00:00Z", value=round(v * 1000, 3), unit="MWh",
                freq="P1Y", geo="KZ", market="", node=label, **bases[y])
           for y, vals in sorted(by_year.items()) for item, (v, label) in sorted(vals.items())]
    return pd.DataFrame(out)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Bureau of National Statistics of Kazakhstan: electricity in the fuel and energy balance")
    ap.add_argument("--offline", action="store_true", help="the saved workbooks only, no request")
    ap.add_argument("--fresh", action="store_true", help="ask for the workbooks again")
    ap.add_argument("--out-dir", help="a trial: the table under this folder, not warehouse/output")
    args = ap.parse_args(argv)
    if ip.paused(CONNECTOR) or ip.paused_host(HOST):
        print(f"{NAME}: the publisher is paused (warehouse/metadata/paused_sources.csv); nothing asked")
        return 0
    if args.out_dir:
        raw_dir = ip.RAW_DIR
        ip.set_out_dir(args.out_dir)
        ip.RAW_DIR = raw_dir
    os.makedirs(ip.LOG_DIR, exist_ok=True)
    run_id = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = ip.Log(os.path.join(ip.LOG_DIR, f"{CONNECTOR}_{run_id}.log"))
    ip.RAW.open(CONNECTOR, run_id)
    results = []
    try:
        by_year, bases = {}, {}
        for y, el in sorted(FILES.items()):
            url = URL.format(el)
            content, rec = ip.fetch_raw(CONNECTOR, url, log, offline=args.offline, fresh=args.fresh, headers=UA, timeout=180, pause=1)
            wb = openpyxl.load_workbook(io.BytesIO(content), data_only=True, read_only=True)
            if SHEET not in wb.sheetnames:
                raise RuntimeError(f"{y}: no sheet {SHEET!r}: {wb.sheetnames}")
            by_year[y] = parse_sheet([tuple(r) for r in wb[SHEET].iter_rows(values_only=True)], y)
            bases[y] = dict(source=SOURCE, source_url=url, retrieved_at=rec.get("retrieved_at") or "", vintage=ip.vintage_of(rec))
        t = frame(by_year, bases)
        if t.duplicated(["entity", "variable", "ts_utc"]).any():
            raise RuntimeError("a key given twice")
        cols = ip.SERIES_COLS + X_COLS
        t = t[cols].sort_values(["entity", "ts_utc"]).reset_index(drop=True)
        out = t[t.entity == "statkz:kz:output"].set_index("ts_utc").value
        head = [
            "Energy Research Warehouse (ERW): Bureau of National Statistics of Kazakhstan, fuel and energy balances in physical terms, "
            f"the electricity column: Kazakhstan's electricity output, trade and use, {t.ts_utc.min()[:4]} to {t.ts_utc.max()[:4]} "
            "(session 2664)",
            "Shape: series (docs/datastandard.md v0). entity statkz:kz:<item>; variable generation, imports, exports (positive), "
            "own_use, losses, consumption or statistical_difference; unit MWh (the balance's million kWh times 1,000); ts_utc the "
            "year's first day; freq P1Y; geo KZ; node the row's label.",
            f"{len(t)} rows; the output, TWh: " + ", ".join(f"{k[:4]} {v / 1e6:.1f}" for k, v in out.items())
            + ". Plant classes, the balance and the sectors checked against their totals; nothing is filled.",
            f"Retrieved: {run_id} (UTC) by warehouse/connectors/stat_kz_kazakhstan_electricity.py; the workbooks retrieved "
            + ", ".join(f"{y} {b['retrieved_at']}" for y, b in sorted(bases.items())),
            f"Run log: warehouse/output/logs/{CONNECTOR}_{run_id}.log",
            f"Raw files: warehouse/raw/{CONNECTOR}/ (not in git)",
            f"Source: {SOURCE} {CITATION}",
            f"  access: {URL.format('<id>')} (one workbook a year; listed on {PAGE})",
            f"License: the Bureau's conditions for the use of official statistical information ({TERMS}): free use with a reference "
            "to the source. Credit: Bureau of National Statistics of the Agency for Strategic Planning and Reforms of the Republic of "
            "Kazakhstan.",
        ]
        ip.write_snapshot(t, NAME, head, log, cols)
        results.append(dict(table=NAME, market="all", status="ok", detail=f"{len(t)} rows"))
        print(f"{NAME}: {len(t)} rows, {t.entity.nunique()} entities")
    except Exception:
        tb = ip.redact(traceback.format_exc())
        log(f"{NAME} FAILED, no output file written:\n{tb}")
        print(f"{NAME} FAILED, no output file written: {tb.strip().splitlines()[-1]}", file=sys.stderr)
        results.append(dict(table=NAME, market="all", status="failed", detail=tb.strip().splitlines()[-1][:300]))
    if not args.out_dir:
        if results and results[0]["status"] == "ok":
            ip.update_sources([dict(source=SOURCE, publisher="Bureau of National Statistics of Kazakhstan",
                                    report="Fuel and energy balance of the Republic of Kazakhstan, in physical terms (2022 to 2025), the "
                                           "electricity column", report_url=PAGE, document_list=PAGE, license="public", tables=[NAME])])
        ip.write_status(CONNECTOR, run_id, results)
    log.close()
    return 0 if all(r["status"] == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
