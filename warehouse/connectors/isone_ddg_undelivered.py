#!/usr/bin/env python3
"""ISO-NE: delivered and undelivered energy of its dispatchable wind and solar plants, monthly (session 149). INTERNAL.

Energy Research Warehouse (ERW) connector. One series table, warehouse/output/isone_ddg_undelivered_monthly.csv, from
ISO New England's ISO Express report "Aggregate Monthly DDG Undelivered Energy" (DDG: Do Not Exceed Dispatchable
Generator, ISO-NE's name for a wind or solar plant it dispatches by a limit):

    https://www.iso-ne.com/isoexpress/web/reports/operations/-/tree/aggregate-monthly-ddg-undelivered-energy   the page
    https://www.iso-ne.com/isoexpress/web/reports/download/docWidgetGetMore?start=0&treenode=aggregate-monthly-ddg-undelivered-energy
                                                                                                              its file list (JSON)
    https://www.iso-ne.com/static-assets/documents/<folder>/<file>.xlsx                                       a year's workbook

    python warehouse/connectors/isone_ddg_undelivered.py --pull [--limit N] [--reuse-list] [--raw-dir DIR]   # save ISO-NE's files (no data lock)
    python warehouse/connectors/isone_ddg_undelivered.py --write [--out-dir DIR] [--raw-dir DIR]             # build the table from them

THE RULING. The owner's of 7 October 2026: the file is pulled and held internal, about 1,000 rows. It is ISO-NE's own
monthly figure of what its wind and solar plants could have delivered and did not, the nearest thing ISO-NE publishes
to a curtailment series (session 144 found it and did not pull it). It is shown on no page: the curtailment page's
ISO-NE entry stays a placeholder.

THE WORKBOOK. One a year and fuel (wind from 2018, solar from 2025), named in ISO-NE's list "<YYYY> Undelivered Wind
(or Solar) Energy Aggregate Report". A sheet "Nomenclature" and seven sheets of twelve month lines, "<YYYY> System",
"<YYYY> ME", "<YYYY> System wo ME", "<YYYY> ORR_SO", "<YYYY> System wo ORR_SO", "<YYYY> Congested", "<YYYY>
Uncongested", each with the columns DE [MWH], UE [MWH], UE-NonBind [MWH], UE-Bind [MWH], percent UE, percent
UE-NonBind, percent UE-Bind. Every sheet is marked "ISO-NE Public". ISO-NE's own definitions (sheet Nomenclature):

    "Delivered Energy: the amount of energy generated by the plant."
    "Estimated Undelivered Energy is the sum of the UE-Non-Bind and UE-Bind (described below)"
    "UE-Non-Bind: undelivered energy during one or more time periods where a wind plant did not have a sensitivity to
     a binding transmission constraint, this is generally caused by the plant's energy supply offer indicating a
     preference to generate less MW than the theoretical maximum potentially achievable given the conditions at the
     plant."
    "UE-Bind: indicates that a wind plant likely had undelivered energy during one or more periods while the plant
     had a non-zero sensitivity to one or more binding transmission constraints"
    "Percentages in all charts and tables use UE+DE of the respective aggregation to normalize the respective values."

WHAT IS WRITTEN. The sheet "<YYYY> System" only: one row a fuel, month and figure, entity isone:system, freq P1M,
ts_utc the first of the month at 00:00:00Z. Variables <fuel>_delivered_mwh, <fuel>_undelivered_mwh,
<fuel>_undelivered_nonbinding_mwh, <fuel>_undelivered_binding_mwh (MWh, as printed) and <fuel>_undelivered_pct,
<fuel>_undelivered_nonbinding_pct, <fuel>_undelivered_binding_pct (ISO-NE's own fraction of UE + DE, times 100).
A blank cell (a month not yet published) is no row. A cell that is neither blank nor a number stops the read. Nothing
is summed, filled or estimated here. The six other sheets (Maine, the Orrington South interface, the congested and
uncongested groups) stay in the saved workbooks and are NOT in the table: with them the table would pass the ceiling.

THE CEILING, over every run of this connector (the manifest counts each request, and the rows are counted from the
workbooks kept, each as the table reads it): 2,000 rows of the series, 20 requests, 50 MB. The stop sits BEFORE the
request that would pass any of the three. The pull is made once; it is on no schedule, and a refresh needs a new
ruling.

HOW IT IS ASKED. A plain request, with the one contact string the ERW sends ("ERW research project,
github.com/SamuelEnrique/erw") and nothing else: no cookie, no account, no address of a person. The page's own
CAPTCHA guards its several-files download form, which is not used; each workbook is asked for at the address the
page's own list gives. An answer that is an access control (401, 403, or a page where a workbook should be) is
recorded and nothing more is asked. One try a request: a request that fails is recorded and left.

License: INTERNAL (the ERW's standing reading for ISO-NE, sessions 65, 85, 136, 138 and 140; the owner's ruling of
7 October 2026 for this file). ISO-NE's legal notice (https://www.iso-ne.com/legal-privacy, read 7 October 2026 and
saved by --pull as legal_notice.html, its hash and retrieval time in the manifest): "You are also hereby put on
notice that the Content is protected by copyright under United States laws. Any duplication of the Content or
non-personal use may violate copyright, trademark, and other laws." The table is not published: it is in no public
dataset, no download, no page.
"""

