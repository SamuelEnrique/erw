CONNECTOR = "isone_ddg_undelivered"
NAME = "isone_ddg_undelivered_monthly"
SOURCE = "isone:ddg_undelivered_monthly"
ENTITY = "isone:system"
GEO = "US-CT,US-MA,US-ME,US-NH,US-RI,US-VT"
NODE = "aggregate-monthly-ddg-undelivered-energy"
HOST = "https://www.iso-ne.com"
PAGE = HOST + "/isoexpress/web/reports/operations/-/tree/" + NODE
LIST = HOST + "/isoexpress/web/reports/download/docWidgetGetMore?start={}&treenode=" + NODE
LEGAL = HOST + "/legal-privacy"
CONTACT = "ERW research project, github.com/SamuelEnrique/erw"
UA = {"User-Agent": CONTACT}
MAX_ROWS, MAX_REQUESTS, MAX_BYTES = 2_000, 20, 50 * 1024 * 1024
ROWS_EST = 84                 # the most one workbook can hold of the series: twelve months, seven figures
BYTES_EST = 2 * 1024 * 1024   # a workbook's size allowed for before it is asked (those read are under 200 kB)
LIST_STEP = 40
PAUSE = 3.0
RAW = os.path.join(ip.RAW_DIR, CONNECTOR)
FILE = re.compile(r"^/static-assets/documents/[A-Za-z0-9_/.-]+\.xlsx$")
DESCRIPTION = re.compile(r"^(\d{4}) Undelivered (Wind|Solar) Energy Aggregate Report$")
SHEET = "System"
MONTHS = ["jan", "feb", "mar", "apr", "may", "jun", "jul", "aug", "sep", "oct", "nov", "dec"]
