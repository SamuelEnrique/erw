def main(argv=None):
    global RAW
    ap = argparse.ArgumentParser(description="ISO-NE's Aggregate Monthly DDG Undelivered Energy (internal)")
    ap.add_argument("--pull", action="store_true", help="save ISO-NE's files (no table is written, no data lock)")
    ap.add_argument("--write", action="store_true", help="build the table from the saved files (the data lock into warehouse/output)")
    ap.add_argument("--limit", type=int, default=10 ** 9, help="pull: at most N workbooks in this run")
    ap.add_argument("--reuse-list", action="store_true", help="pull: read the list saved by an earlier run, not ISO-NE's again (one request fewer)")
    ap.add_argument("--out-dir", help="write: the table under this folder, not warehouse/output (a trial; no data lock)")
    ap.add_argument("--raw-dir", help="another folder for the saved files (the main copy's raw store from a working copy, a trial or a test)")
    args = ap.parse_args(argv)
    if args.raw_dir:
        RAW = os.path.abspath(args.raw_dir)
    if not (args.pull or args.write):
        ap.error("one of --pull, --write")
    code = 0
    if args.pull:
        os.makedirs(RAW, exist_ok=True)
        stamp = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
        with open(os.path.join(RAW, f"pull_{stamp}.log"), "w", encoding="utf-8", newline="\n") as f:
            def say(msg):
                f.write(msg + "\n")
                f.flush()
                print(msg)
            try:
                say(f"ERW {CONNECTOR} --pull {stamp}; ceilings {MAX_ROWS:,} rows, {MAX_REQUESTS} requests, {MAX_BYTES:,} bytes")
                out = pull(say, args.limit, args.reuse_list)
            except (CeilingStop, AccessStop) as exc:
                out = f"stopped: {exc}"
                code = 1
            except Exception:
                out = "failed: " + traceback.format_exc().strip().splitlines()[-1]
                say(traceback.format_exc())
                code = 1
            rows, reqs, nbytes = counted()
            say(f"pull: {out}. In all: {rows:,} rows of the series in the workbooks kept (ceiling {MAX_ROWS:,}); {reqs} requests (ceiling {MAX_REQUESTS}); "
                f"{nbytes:,} bytes (ceiling {MAX_BYTES:,})")
    if args.write and code == 0:
        code = write(args.out_dir)
    return code


if __name__ == "__main__":
    sys.exit(main())
