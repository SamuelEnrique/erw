#!/usr/bin/env python3
"""Zimbabwe's electricity generation, a month, January 2019 to March 2026, as the Zimbabwe National Statistics Agency
(ZIMSTAT) gives it in Appendix A of its Index of Electricity Generation, 1st Quarter 2026 (session 2491, chain 121).

Energy Research Warehouse (ERW) connector. One series table,
warehouse/output/zimstat_zimbabwe_generation_monthly.csv, from one PDF (no key):

    https://www.zimstat.co.zw/wp-content/uploads/production/Energy/2026/Q1/IEG_Q1_2026.pdf

ZIMSTAT compiles the index from the Zimbabwe Electricity Supply Authority's (ZESA) administrative data: the volume
generated by Hwange, Kariba and the independent power producers together. "Appendix A: Volume of Electricity Generation
in GWh" is read as text: a header of the years 2019 to 2026, twelve month rows and four quarter rows, each row's figures
in the years' order (the newest year's column ends where the publication ends, so a row holds seven or eight figures).

    entity      zimstat:zw:total
    variable    generation
    unit        MWh (ZIMSTAT's GWh times 1,000)
    ts_utc      the month's first day, 00:00 UTC; freq P1M; geo ZW
    node        the month as ZIMSTAT labels it

The quarter rows are not written: each is compared with its three months' sum, and the count that agree within 0.15 GWh
goes in the header. A figure not in the form of the table (a comma where the table prints a decimal point, as
"971,5" for January 2026) has no row and is counted in the header. A publication without the appendix, a header other
than the eight years, a month row with fewer than seven or more than eight figures, or a key given twice stops the run.
Nothing is filled. The index itself, imports, exports and distribution (drawn as charts) are not taken.

    python warehouse/connectors/zimstat_zimbabwe_generation.py [--offline] [--out-dir DIR]

Ceiling: one request a run, saved in warehouse/raw/zimstat_electricity_index/ and reused unless --fresh; --offline asks
nothing. zimstat.co.zw's robots file disallows nothing (session 2491). License: not settled. ZIMSTAT's copyright page:
"Unless otherwise stated, the material or information published within the Zimbabwe National Statistics Agency Website
is ZIMSTAT copyright"; no grant of reuse. Internal until a ruling.
"""

import argparse
import datetime as dt
import io
import os
import re
import sys
import traceback

import pandas as pd
import pdfplumber

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import iso_prices as ip  # noqa: E402

NAME = "zimstat_zimbabwe_generation_monthly"
CONNECTOR = "zimstat_electricity_index"
SOURCE = "zimstat:index_of_electricity_generation"
HOST = "www.zimstat.co.zw"
URL = "https://www.zimstat.co.zw/wp-content/uploads/production/Energy/2026/Q1/IEG_Q1_2026.pdf"
UA = {"User-Agent": "Mozilla/5.0 (compatible; ERW-connector/0.1; +https://github.com/SamuelEnrique/erw)"}
YEARS = [str(y) for y in range(2019, 2027)]
MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October", "November", "December"]
FORM = r"\d{1,3}(,\d{3})*\.\d+"
X_COLS = ["x_label"]


def appendix_lines(text):
    """The lines of Appendix A after its header of years, up to Appendix B."""
    i = [m.start() for m in re.finditer(r"Appendix A: Volume of Electricity Generation", text)]
    for start in i:
        part = text[start:]
        end = part.find("Appendix B:")
        lines = [ln.strip() for ln in (part[:end] if end > 0 else part).splitlines()]
        if any(ln.split() == YEARS for ln in lines):
            k = next(j for j, ln in enumerate(lines) if ln.split() == YEARS)
            return lines[k + 1:]
    raise RuntimeError("Appendix A with its header of the years 2019 to 2026 not found")


def parse_text(text, base, counts):
    out, seen, quarters = [], set(), {}
    for ln in appendix_lines(text):
        toks = ln.split()
        if not toks:
            continue
        label = toks[0]
        if label in MONTHS:
            figs = toks[1:]
            if not len(YEARS) - 1 <= len(figs) <= len(YEARS):
                raise RuntimeError(f"{label}: {len(figs)} figures, not {len(YEARS) - 1} or {len(YEARS)}")
            m = MONTHS.index(label) + 1
            for year, tok in zip(YEARS, figs):
                if not re.fullmatch(FORM, tok):
                    counts["figures out of form"] = counts.get("figures out of form", 0) + 1
                    continue
                key = (year, m)
                if key in seen:
                    raise RuntimeError(f"{key} given twice")
                seen.add(key)
                out.append(dict(entity="zimstat:zw:total", variable="generation", ts_utc=f"{year}-{m:02d}-01T00:00:00Z",
                                value=round(float(tok.replace(",", "")) * 1000, 3), unit="MWh", freq="P1M", geo="ZW", market="",
                                node=f"{label} {year}", **base, x_label=f"{label} {year}"))
        elif re.fullmatch(r"Q[1-4]", label):
            for year, tok in zip(YEARS, toks[1:]):
                if re.fullmatch(FORM, tok):
                    quarters[(year, int(label[1]))] = float(tok.replace(",", ""))
    t = pd.DataFrame(out)
    if t.empty:
        raise RuntimeError("no figure in Appendix A")
    agree, compared = 0, 0
    gwh = {(r[:4], int(r[5:7])): v / 1000 for r, v in zip(t.ts_utc, t.value)}
    for (year, q), v in quarters.items():
        ms = [gwh.get((year, 3 * (q - 1) + k)) for k in (1, 2, 3)]
        if None in ms:
            continue
        compared += 1
        agree += abs(sum(ms) - v) <= 0.15
    counts["quarters compared"] = compared
    counts["quarters agreeing"] = agree
    return t


def parse(content, base, counts):
    with pdfplumber.open(io.BytesIO(content)) as pdf:
        text = "\n".join(pg.extract_text() or "" for pg in pdf.pages)
    return parse_text(text, base, counts)


def main(argv=None):
    ap = argparse.ArgumentParser(description="ZIMSTAT: Zimbabwe's monthly electricity generation, 2019 to 2026")
    ap.add_argument("--offline", action="store_true", help="the saved publication only, no request")
    ap.add_argument("--fresh", action="store_true", help="ask for the publication again")
    ap.add_argument("--out-dir", help="a trial: the table under this folder, not warehouse/output")
    args = ap.parse_args(argv)
    if ip.paused(CONNECTOR) or ip.paused_host(HOST) or ip.paused_host("zimstat.co.zw"):
        print(f"{NAME}: the publisher is paused (warehouse/metadata/paused_sources.csv); nothing asked")
        return 0
    if args.out_dir:
        raw_dir = ip.RAW_DIR
        ip.set_out_dir(args.out_dir)
        ip.RAW_DIR = raw_dir
    os.makedirs(ip.LOG_DIR, exist_ok=True)
    run_id = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = ip.Log(os.path.join(ip.LOG_DIR, f"{CONNECTOR}_{run_id}.log"))
    ip.RAW.open(CONNECTOR, run_id)
    results = []
    try:
        content, rec = ip.fetch_raw(CONNECTOR, URL, log, offline=args.offline, fresh=args.fresh, headers=UA, timeout=180, pause=1)
        base = dict(source=SOURCE, source_url=URL, retrieved_at=rec.get("retrieved_at") or "", vintage=ip.vintage_of(rec))
        counts = {}
        t = parse(content, base, counts)
        cols = ip.SERIES_COLS + X_COLS
        t = t[cols].sort_values(["ts_utc"]).reset_index(drop=True)
        y = t.assign(year=t.ts_utc.str[:4]).groupby("year").value.agg(["sum", "count"])
        head = [
            "Energy Research Warehouse (ERW): Zimbabwe National Statistics Agency (ZIMSTAT), Index of Electricity Generation, 1st Quarter 2026, Appendix A, "
            f"Zimbabwe's electricity generation a month, {t.ts_utc.min()[:7]} to {t.ts_utc.max()[:7]} (session 2491)",
            "Shape: series (docs/datastandard.md v0). entity zimstat:zw:total (Hwange, Kariba and the independent power producers, from ZESA's administrative data); "
            "variable generation; unit MWh (ZIMSTAT's GWh times 1,000); ts_utc the month's first day; freq P1M; geo ZW; node the month as ZIMSTAT labels it.",
            f"{len(t)} rows; full years' generation TWh: " + ", ".join(f"{k} {r['sum'] / 1e6:.2f}" for k, r in y.iterrows() if r["count"] == 12)
            + f". Quarter rows not written: {counts.get('quarters agreeing', 0)} of {counts.get('quarters compared', 0)} agree with their months' sum within 0.15 GWh. "
            f"Not taken: figures out of form {counts.get('figures out of form', 0)}. Nothing is filled.",
            f"Retrieved: {run_id} (UTC) by warehouse/connectors/zimstat_zimbabwe_generation.py; the publication retrieved {base['retrieved_at']}; last modified {base['vintage']}",
            f"Run log: warehouse/output/logs/{CONNECTOR}_{run_id}.log",
            f"Raw files: warehouse/raw/{CONNECTOR}/ (not in git)",
            f"Source: {SOURCE} ZIMSTAT, Index of Electricity Generation, 1st Quarter 2026, Appendix A: Volume of Electricity Generation in GWh, 2019 to 1st Quarter 2026",
            f"  access: {URL}",
            "License: internal (ZIMSTAT's copyright page: the website's material is ZIMSTAT copyright unless otherwise stated; no grant of reuse).",
        ]
        ip.write_snapshot(t, NAME, head, log, cols)
        results.append(dict(table=NAME, market="all", status="ok", detail=f"{len(t)} rows"))
        print(f"{NAME}: {len(t)} rows; {counts}")
    except Exception:
        tb = ip.redact(traceback.format_exc())
        log(f"{NAME} FAILED, no output file written:\n{tb}")
        print(f"{NAME} FAILED, no output file written: {tb.strip().splitlines()[-1]}", file=sys.stderr)
        results.append(dict(table=NAME, market="all", status="failed", detail=tb.strip().splitlines()[-1][:300]))
    if not args.out_dir:
        if results and results[0]["status"] == "ok":
            ip.update_sources([dict(source=SOURCE, publisher="Zimbabwe National Statistics Agency (ZIMSTAT)",
                                    report="Index of Electricity Generation, 1st Quarter 2026, Appendix A (generation a month, GWh)", report_url=URL,
                                    document_list="https://zimstat.co.zw/", license="internal", tables=[NAME])])
        ip.write_status(CONNECTOR, run_id, results)
    log.close()
    return 0 if all(r["status"] == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
