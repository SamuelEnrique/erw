#!/usr/bin/env python3
"""The UK's electricity generated and supplied by fuel, a quarter, from the Department for Energy Security and Net Zero's
Energy Trends table 5.1 (session 2168, chain 094: the UK's generation mix beside the U.S. grids', a source of the
session's own choosing).

Energy Research Warehouse (ERW) connector. One series table, warehouse/output/desnz_uk_electricity_quarterly.csv, from
the Energy Trends section 5 page's table ET 5.1 (an xlsx on assets.publishing.service.gov.uk), its sheet "Quarter":

    https://www.gov.uk/government/statistics/electricity-section-5-energy-trends     (the page, for the file's address)

The sheet holds four tables one under another; two are taken, each row a generator type and fuel:

    Table 5.1b: electricity generated by fuel (TWh)   -> variable generated
    Table 5.1c: electricity supplied by fuel (TWh)    -> variable supplied (net of the stations' own use; pumped storage
                                                         as its net supply, which is negative; net imports a row of it)

Table 5.1a (fuel used, in Mtoe and million tonnes) and 5.1d (shares) are not taken.

    entity      desnz_et51:<generator type>:<fuel>, both in snake case as the sheet names them (major_power_producers,
                other_generators, all_generating_companies; coal, gas, nuclear, total_wind, onshore_wind, offshore_wind,
                solar, bioenergy, pumped_storage, battery_storage, net_imports, total_all_generating_companies...);
                node the generator type and fuel in DESNZ's words. Totals are DESNZ's rows, never sums made here, and a
                sum over the fuels must leave the totals out (and total_wind with onshore and offshore)
    unit        MWh (DESNZ's TWh times 1,000,000)
    ts_utc      the quarter's first day at 00:00:00Z; freq P3M; geo GB (the United Kingdom)

"[x]" (no figure) has no row; nothing is filled. A quarter DESNZ marks "[provisional]" is kept, x_provisional yes (it is
revised in a later issue). A sheet without the two tables, a column header not "Quarter <n> <year>" (with or without
" [provisional]"), a value that is neither a number nor "[x]", or a key given twice stops the run.

    python warehouse/connectors/desnz_energy_trends.py [--offline] [--out-dir DIR]

Ceiling: two requests (the page and the file it links), reused from warehouse/raw/desnz_energy_trends/ with
--offline. www.gov.uk's robots file disallows print and search pages only, and assets.publishing.service.gov.uk has no
robots file (session 2168). License: the Open Government Licence v3.0 (GOV.UK's licence for its content, record 315);
attribution: "Contains public sector information licensed under the Open Government Licence v3.0".
"""

import argparse
import datetime as dt
import io
import os
import re
import sys
import traceback

import openpyxl
import pandas as pd

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import iso_prices as ip  # noqa: E402

NAME = "desnz_uk_electricity_quarterly"
CONNECTOR = "desnz_energy_trends"
SOURCE = "desnz:energy_trends_5_1"
PAGE = "https://www.gov.uk/government/statistics/electricity-section-5-energy-trends"
UA = {"User-Agent": "Mozilla/5.0 (compatible; ERW-connector/0.1; +https://github.com/SamuelEnrique/erw)"}
TABLES = {"Table 5.1b: electricity generated by fuel (TWh)": "generated",
          "Table 5.1c: electricity supplied by fuel (TWh)": "supplied"}
QUARTER = re.compile(r"^Quarter ([1-4]) (\d{4})( \[provisional\])?$")
COLS = ["entity", "variable", "ts_utc", "value", "unit", "freq", "geo", "market", "node", "source", "source_url",
        "retrieved_at", "vintage", "x_generator_type", "x_fuel", "x_provisional"]


def text(v):
    return re.sub(r"\s+", " ", str(v if v is not None else "")).strip()


def slug(s):
    return re.sub(r"[^a-z0-9]+", "_", re.sub(r"\(.*?\)|\[.*?\]", "", s.lower())).strip("_")


def build(workbook, url, retrieved, vintage):
    wb = openpyxl.load_workbook(io.BytesIO(workbook), read_only=True, data_only=True)
    if "Quarter" not in wb.sheetnames:
        raise RuntimeError(f"no sheet 'Quarter': {wb.sheetnames}")
    rows = [list(r) for r in wb["Quarter"].iter_rows(values_only=True)]
    out, found = [], set()
    i = 0
    while i < len(rows):
        title = text(rows[i][0])
        if title in TABLES:
            var = TABLES[title]
            found.add(title)
            head = rows[i + 1]
            if text(head[0]) != "Generator type" or text(head[1]) != "Fuel":
                raise RuntimeError(f"{title}: no 'Generator type, Fuel' header under it")
            cols = []
            for j, h in enumerate(head[2:], start=2):
                h = text(h)
                if not h:
                    continue
                m = QUARTER.fullmatch(h)
                if not m:
                    raise RuntimeError(f"{title}: a column header not 'Quarter <n> <year>': {h!r}")
                q, y = int(m.group(1)), int(m.group(2))
                cols.append((j, f"{y}-{3 * q - 2:02d}-01T00:00:00Z", "yes" if m.group(3) else "no"))
            i += 2
            while i < len(rows) and text(rows[i][0]) and not text(rows[i][0]).startswith("Table "):
                gen, fuel = text(rows[i][0]), text(rows[i][1])
                for j, ts, prov in cols:
                    v = rows[i][j] if j < len(rows[i]) else None
                    if v is None or text(v) == "[x]":
                        continue
                    if not isinstance(v, (int, float)):
                        raise RuntimeError(f"{title}: {gen}, {fuel}, {ts[:7]}: not a number: {v!r}")
                    out.append({"entity": f"desnz_et51:{slug(gen)}:{slug(fuel)}", "variable": var, "ts_utc": ts,
                                "value": round(float(v) * 1_000_000, 3), "unit": "MWh", "freq": "P3M", "geo": "GB",
                                "market": "", "node": f"{gen}, {fuel}", "source": SOURCE, "source_url": url,
                                "retrieved_at": retrieved, "vintage": vintage, "x_generator_type": gen, "x_fuel": fuel,
                                "x_provisional": prov})
                i += 1
            continue
        i += 1
    missing = set(TABLES) - found
    if missing:
        raise RuntimeError(f"the sheet lacks {sorted(missing)}")
    t = pd.DataFrame(out, columns=COLS)
    twice = t[t.duplicated(["entity", "variable", "ts_utc"], keep=False)]
    if len(twice):
        raise RuntimeError(f"a key given twice: {twice.entity.iloc[0]} {twice.variable.iloc[0]} {twice.ts_utc.iloc[0]}")
    return t.sort_values(["variable", "entity", "ts_utc"]).reset_index(drop=True)


def main(argv=None):
    ap = argparse.ArgumentParser(description="DESNZ Energy Trends 5.1: UK electricity generated and supplied by fuel, a quarter")
    ap.add_argument("--offline", action="store_true", help="the saved files only, no request")
    ap.add_argument("--out-dir", help="a trial: the table under this folder, not warehouse/output")
    args = ap.parse_args(argv)
    if args.out_dir:
        raw_dir = ip.RAW_DIR
        ip.set_out_dir(args.out_dir)
        ip.RAW_DIR = raw_dir
    os.makedirs(ip.LOG_DIR, exist_ok=True)
    run_id = dt.datetime.now(dt.timezone.utc).strftime("%Y%m%dT%H%M%SZ")
    log = ip.Log(os.path.join(ip.LOG_DIR, f"{CONNECTOR}_{run_id}.log"))
    ip.RAW.open(CONNECTOR, run_id)
    results = []
    try:
        if not args.offline and (ip.paused("desnz") or ip.paused_host("www.gov.uk") or ip.paused_host("assets.publishing.service.gov.uk")):
            raise RuntimeError("DESNZ is paused (warehouse/metadata/paused_sources.csv): not requested")
        page, _ = ip.fetch_raw(CONNECTOR, PAGE, log, offline=args.offline, fresh=not args.offline, headers=UA, timeout=120)
        links = re.findall(r'href="(https://assets\.publishing\.service\.gov\.uk/[^"]*/ET_5\.1_[^"]*\.xlsx)"', page.decode("utf-8", errors="replace"))
        if not links:
            raise RuntimeError(f"{PAGE} links no ET 5.1 workbook")
        url = links[0]
        content, rec = ip.fetch_raw(CONNECTOR, url, log, offline=args.offline, headers=UA, timeout=300)
        t = build(content, url, rec.get("retrieved_at") or "", ip.vintage_of(rec))
        tot = t[(t.entity == "desnz_et51:all_generating_companies:total_all_generating_companies") & (t.variable == "generated")]
        header = [
            f"Energy Research Warehouse (ERW): UK Department for Energy Security and Net Zero (DESNZ), Energy Trends table 5.1, electricity generated and supplied by fuel, a quarter, {t.ts_utc.min()[:7]} to {t.ts_utc.max()[:7]} (session 2168)",
            "Shape: series (docs/datastandard.md v0). entity desnz_et51:<generator type>:<fuel>; variable generated (table 5.1b) or supplied (5.1c); unit MWh (DESNZ's TWh times 1,000,000); "
            "ts_utc the quarter's first day; freq P3M; geo GB. Totals are DESNZ's own rows: a sum over the fuels must leave them out, and total_wind with its parts.",
            f"{len(t)} rows, {t.entity.nunique()} generator type and fuel rows; the UK's total generated in the latest quarter, {tot.ts_utc.max()[:7]}: {tot.value.iloc[-1] / 1e6:,.1f} TWh. "
            f"{(t.x_provisional == 'yes').sum()} rows of quarters DESNZ marks provisional (x_provisional yes). '[x]' (no figure) has no row; nothing is filled. Fuel used (5.1a) and the shares (5.1d) are not taken.",
            f"Retrieved: {run_id} (UTC) by warehouse/connectors/desnz_energy_trends.py; the workbook retrieved {rec.get('retrieved_at') or ''}"
            + (f", last modified {ip.vintage_of(rec)}" if ip.vintage_of(rec) else ""),
            f"Run log: warehouse/output/logs/{CONNECTOR}_{run_id}.log",
            f"Raw files: warehouse/raw/{CONNECTOR}/ (not in git)",
            f"Source: {SOURCE} UK Department for Energy Security and Net Zero, Energy Trends section 5: electricity, table ET 5.1, {PAGE}",
            f"  access: {url}",
            "License: public. Contains public sector information licensed under the Open Government Licence v3.0 (https://www.nationalarchives.gov.uk/doc/open-government-licence/version/3/).",
        ]
        ip.write_csv(t, NAME, header, log, cols=COLS)
        if not args.out_dir:
            ip.update_sources([dict(source=SOURCE, publisher="UK Department for Energy Security and Net Zero (DESNZ)",
                                    report="Energy Trends section 5: electricity, table ET 5.1 (fuel used in generation and electricity supplied)",
                                    report_url=PAGE, document_list=url, license="public", tables=[NAME])])
        results.append(dict(table=NAME, market="all", status="ok", detail=f"{len(t)} rows"))
        print(f"{NAME}: {len(t)} rows, {t.ts_utc.min()[:7]} to {t.ts_utc.max()[:7]}")
    except Exception:
        tb = ip.redact(traceback.format_exc())
        log(f"FAILED, no output file written:\n{tb}")
        print(f"{CONNECTOR} FAILED, no output file written: {tb.strip().splitlines()[-1]}", file=sys.stderr)
        results.append(dict(table=NAME, market="all", status="failed", detail=tb.strip().splitlines()[-1][:300]))
    if not args.out_dir:
        ip.write_status(CONNECTOR, run_id, results)
    log.close()
    return 0 if all(r["status"] == "ok" for r in results) else 1


if __name__ == "__main__":
    sys.exit(main())
